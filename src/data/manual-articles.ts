export const ALL_MANUAL_ARTICLES = [...MANUAL_ARTICLES, ...SCHEDULED_ARTICLES];

/**
 * Returns only articles that are published as of now (server/client local time)
 */
export function getActiveManualArticles(currentDateStr?: string): ManualArticle[] {
  const targetDate = currentDateStr || new Date().toISOString().split("T")[0];
  return ALL_MANUAL_ARTICLES.filter(article => article.publishedAt <= targetDate);
}

export function getManualArticleBySlug(slug: string): ManualArticle | undefined {
  const cleanSlug = slug.trim().toLowerCase().replace(/^\/post\//, "").replace(/\/$/, "");
  return ALL_MANUAL_ARTICLES.find(a => a.slug.toLowerCase() === cleanSlug);
}
